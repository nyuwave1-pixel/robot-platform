// Writes the parity fixture for Core/IslandTerrain.cs from the web game's terrain module (the source of truth).
//   node "apps/unity-studio/Tools~/gen-terrain-fixture.mjs"
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FLATS, rawHeight, splatAt } from '../../special-soldier/src/world/terrain.js';
import { fbm, noise2 } from '../../special-soldier/src/core/util.js';

const here = dirname(fileURLToPath(import.meta.url));
const d = (x) => x.toPrecision(17);
let seed = 12345; const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
const pts = [];
for (let x = -600; x <= 600; x += 60) for (let z = -600; z <= 600; z += 60) pts.push([x, z]);           // coarse grid incl. sea
for (const f of FLATS) for (let k = 0; k < 12; k++) pts.push([f.x0 - 40 + rnd() * (f.x1 - f.x0 + 80), f.z0 - 40 + rnd() * (f.z1 - f.z0 + 80)]); // around the flats
for (let k = 0; k < 120; k++) pts.push([-600 + rnd() * 1200, -600 + rnd() * 1200]);                     // random
const heights = pts.map(([x, z]) => `            (${d(x)}, ${d(z)}, ${d(rawHeight(x, z))}),`);
const splats = pts.filter((_, i) => i % 4 === 0).map(([x, z]) => { const w = splatAt(x, z); return `            (${d(x)}, ${d(z)}, ${w.map(d).join(', ')}),`; });
const noise = [[0.5, 0.5], [12.3, -4.7], [-100.25, 33.5], [1e3 + 0.1, -2e3 + 0.9]].map(([x, y]) => `            (${d(x)}, ${d(y)}, ${d(noise2(x, y))}, ${d(fbm(x, y, 5))}),`);
writeFileSync(join(here, '..', 'Assets', 'Tests', 'EditMode', 'TerrainFixture.g.cs'), `// <auto-generated> by apps/unity-studio/Tools~/gen-terrain-fixture.mjs from apps/special-soldier/src/world/terrain.js. Do not edit.
namespace SpecialSoldier.Core.Tests
{
    public static class TerrainFixture
    {
        public static readonly (double x, double z, double h)[] Heights =
        {
${heights.join('\n')}
        };
        public static readonly (double x, double z, double sand, double grass, double rock, double concrete)[] Splats =
        {
${splats.join('\n')}
        };
        public static readonly (double x, double y, double noise2, double fbm5)[] Noise =
        {
${noise.join('\n')}
        };
    }
}
`);
console.log(`[terrain] ${heights.length} heights, ${splats.length} splats, ${noise.length} noise samples`);
