// Writes the parity fixture for Core/Survival/SurvivalRules.cs from the web prototype (the source of truth):
//   node "apps/unity-studio/Tools~/gen-survival-fixture.mjs"
// Heights and biomes on a grid, the resource-node layout and spawn for two seeds, the rng start for a large seed, and a
// scripted night (wolves spawn from the shared rng, hunt, bite, flee a campfire) — the C# port must reproduce all of it.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const L = await import('../../game-lab/survival-world/src/logic.js');

const seeds = [7, 2026], samples = [];
for (const seed of seeds) for (let x = -200; x <= 200; x += 40) for (let z = -200; z <= 200; z += 40) samples.push([seed, x + 0.5, z - 0.25, L.heightAt(seed, x + 0.5, z - 0.25), L.biomeAt(seed, x + 0.5, z - 0.25)]);
const worlds = seeds.map((seed) => { const W = L.makeWorld(seed); const k = {}; for (const n of W.nodes) k[n.kind] = (k[n.kind] || 0) + 1;
  return { seed, count: W.nodes.length, tree: k.tree || 0, rock: k.rock || 0, bush: k.bush || 0, spawn: [W.spawn.x, W.spawn.z], first: W.nodes.filter((_, i) => i % 37 === 0).slice(0, 25).map((n) => [n.id, n.kind, n.x, n.z, n.y]) }; });
const bigSeed = 758020816, bigRng = L.newGame(bigSeed).rng;
// a scripted night: seed 11, from 19:40, a campfire 4 m east, 0.25 s steps
const G = L.newGame(11); G.time = L.DAY * 0.82; G.structures.push({ kind: 'campfire', x: L.snap(G.player.x + 4), z: L.snap(G.player.z), rot: 0 });
const trace = [];
for (let i = 1; i <= 240; i++) { L.step(G, 0.25); if (i % 20 === 0) trace.push([i, G.player.hp, G.player.warmth, G.wolves.length, G.wolves[0] ? G.wolves[0].x : 0, G.wolves[0] ? G.wolves[0].z : 0, G.rng]); }

const n = (v) => (Number.isInteger(v) ? v.toFixed(1) : v.toPrecision(17));
const cs = `// <auto-generated> by apps/unity-studio/Tools~/gen-survival-fixture.mjs from apps/game-lab/survival-world/src/logic.js. Do not edit.
namespace SurvivalWorld.Tests
{
    public static class SurvivalFixture
    {
        // seed, x, z, height, biome
        public static readonly (long seed, double x, double z, double h, string biome)[] Samples = {
${samples.map((s) => `            (${s[0]}, ${n(s[1])}, ${n(s[2])}, ${n(s[3])}, "${s[4]}"),`).join('\n')}
        };
        public static readonly (long seed, int count, int tree, int rock, int bush, double sx, double sz)[] Worlds = {
${worlds.map((w) => `            (${w.seed}, ${w.count}, ${w.tree}, ${w.rock}, ${w.bush}, ${n(w.spawn[0])}, ${n(w.spawn[1])}),`).join('\n')}
        };
        // seed, node id, kind, x, z, y  (every 37th node)
        public static readonly (long seed, int id, string kind, double x, double z, double y)[] Nodes = {
${worlds.flatMap((w) => w.first.map((f) => `            (${w.seed}, ${f[0]}, "${f[1]}", ${n(f[2])}, ${n(f[3])}, ${n(f[4])}),`)).join('\n')}
        };
        public const long BigSeed = ${bigSeed}; public const uint BigSeedRng = ${bigRng}u;
        // step, hp, warmth, wolves, first wolf x, z, rng — seed 11 from 19:40 with a campfire 4 m east, 0.25 s steps
        public static readonly (int step, double hp, double warmth, int wolves, double wx, double wz, uint rng)[] Night = {
${trace.map((t) => `            (${t[0]}, ${n(t[1])}, ${n(t[2])}, ${t[3]}, ${n(t[4])}, ${n(t[5])}, ${t[6]}u),`).join('\n')}
        };
    }
}
`;
writeFileSync(join(here, '..', 'Assets', 'Tests', 'EditMode', 'SurvivalFixture.g.cs'), cs);
console.log(`SurvivalFixture.g.cs: ${samples.length} samples, ${worlds.length} worlds, night trace ${trace.length} rows (wolves at end ${G.wolves.length}, hp ${G.player.hp.toFixed(1)})`);
