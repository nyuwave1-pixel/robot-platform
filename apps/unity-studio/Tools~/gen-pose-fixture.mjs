// Parity fixture for Core/SoldierPose.cs from the web game's poseSoldier() (src/game/models.js, the source of truth).
//   node "apps/unity-studio/Tools~/gen-pose-fixture.mjs"
// models.js imports three.js and Vite-only asset globs, so the function's own source is cut out and run on stand-in pivots.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { damp } from '../../special-soldier/src/core/util.js';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, '..', '..', 'special-soldier', 'src', 'game', 'models.js'), 'utf8');
const start = src.indexOf('export function poseSoldier(');
if (start < 0) throw new Error('poseSoldier not found in models.js');
let depth = 0, end = src.indexOf(') {', start) + 2;   // the body brace, after the destructured options
for (let i = end; i < src.length; i++) { if (src[i] === '{') depth++; else if (src[i] === '}' && --depth === 0) { end = i + 1; break; } }
const poseSoldier = new Function(`return (${src.slice(start + 'export '.length, end)})`)();

const node = () => ({ rotation: { x: 0 }, position: { y: 0 } });
const rig = () => { const parts = {}; for (const k of ['body', 'legL', 'legR', 'shinL', 'shinR', 'upper', 'head', 'arms', 'gun']) parts[k] = node(); return { userData: { parts }, rotation: { x: 0 }, position: { y: 0 } }; };
const d = (x) => x.toPrecision(17);
const cases = [];
for (const walk of [0, 0.7, 2.1, 3.9, 5.5]) for (const moveK of [0, 0.4, 1]) for (const crouch of [0, 0.5, 1]) for (const aim of [-0.25, 0.3])
  cases.push({ walk, moveK, crouch, aim, sit: false, dead: 0 });
cases.push({ walk: 0, moveK: 0, crouch: 0, aim: 0, sit: true, dead: 0 }, { walk: 1, moveK: 0.5, crouch: 0, aim: 0, sit: false, dead: 1 }, { walk: 1, moveK: 0.5, crouch: 0, aim: 0, sit: false, dead: 0.4 });
const rows = cases.map((c) => {
  const g = rig(); poseSoldier(g, c); const p = g.userData.parts;
  return `            (${d(c.walk)}, ${d(c.moveK)}, ${d(c.crouch)}, ${d(c.aim)}, ${c.sit}, ${d(c.dead)}, ${[p.legL.rotation.x, p.legR.rotation.x, p.shinL.rotation.x, p.shinR.rotation.x, p.upper.rotation.x, p.arms.rotation.x, p.body.position.y, g.rotation.x].map(d).join(', ')}),`;
});
// gait integration (enemies.js): moveK = damp(moveK, moving, 8, dt); walk += speed * dt * 2.6 * moveK; crouch = damp(crouch, want, 9, dt)
let walk = 0.5, moveK = 0, crouch = 0; const gait = [];
for (let i = 0; i < 60; i++) {
  const dt = 1 / 60 + (i % 7) * 0.003, speed = i < 30 ? 1.5 : 3.2, moving = i < 45, want = i >= 40 ? 1 : 0;
  moveK = damp(moveK, moving ? 1 : 0, 8, dt); walk += speed * dt * 2.6 * moveK; crouch = damp(crouch, want, 9, dt);
  if (i % 6 === 5) gait.push(`            (${i}, ${d(walk)}, ${d(moveK)}, ${d(crouch)}),`);
}
writeFileSync(join(here, '..', 'Assets', 'Tests', 'EditMode', 'PoseFixture.g.cs'), `// <auto-generated> by apps/unity-studio/Tools~/gen-pose-fixture.mjs from apps/special-soldier/src/game/models.js poseSoldier(). Do not edit.
namespace SpecialSoldier.Core.Tests
{
    public static class PoseFixture
    {
        /// <summary>(walk, moveK, crouch, aim, sit, dead) → legL, legR, shinL, shinR, upper, arms, body y, model tilt.</summary>
        public static readonly (double walk, double moveK, double crouch, double aim, bool sit, double dead, double legL, double legR, double shinL, double shinR, double upper, double arms, double bodyY, double tilt)[] Poses =
        {
${rows.join('\n')}
        };

        /// <summary>Gait from walk 0.5: frame i has dt = 1/60 + (i % 7) * 0.003, speed 1.5 then 3.2 from frame 30, moving until 45, crouching from 40.</summary>
        public static readonly (int frame, double walk, double moveK, double crouch)[] Gait =
        {
${gait.join('\n')}
        };
    }
}
`);
console.log(`[pose] ${cases.length} poses, ${gait.length} gait samples -> Assets/Tests/EditMode/PoseFixture.g.cs`);
