// Generates the Unity C# copies of the web game's weapon table and a parity fixture, so both engines share one balance.
//   node apps/unity-studio/Tools~/gen-core-data.mjs
// Source of truth: apps/special-soldier/src/config/weapons.js. Re-run after changing it; the C# tests fail on drift.
// (Folders ending in "~" are ignored by Unity's asset importer.)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { WEAPONS, BODY_MULT, damageAt, burstDps, hitChance, cycleTime, effectiveDps, timeToKill } from '../../special-soldier/src/config/weapons.js';

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, '..', 'Assets');
const f = (x) => (Number.isInteger(x) ? `${x}f` : `${x}f`);
const d = (x) => (Number.isFinite(x) ? x.toPrecision(17) : '0'); // full double precision for the fixture
const mode = (m) => `FireMode.${m[0].toUpperCase()}${m.slice(1)}`;
const header = '// <auto-generated> by apps/unity-studio/Tools~/gen-core-data.mjs from apps/special-soldier/src/config/weapons.js. Do not edit.\n';

const rows = Object.entries(WEAPONS).map(([id, w]) => `            ["${id}"] = new WeaponStats("${id}", "${w.name}", "${w.cls}", "${w.slot}", dmg: ${f(w.dmg)}, rpm: ${f(w.rpm)}, mag: ${w.mag}, reserve: ${w.reserve}, reload: ${f(w.reload)},
                ads: ${f(w.ads)}, zoom: ${f(w.zoom)}, recoilV: ${f(w.recoilV)}, recoilH: ${f(w.recoilH)}, spread: ${f(w.spread)}, adsSpread: ${f(w.adsSpread)},
                rangeStart: ${f(w.range[0])}, rangeEnd: ${f(w.range[1])}, minMul: ${f(w.minMul)}, vel: ${f(w.vel)}, weight: ${f(w.weight)}, pellets: ${w.pellets}, loud: ${f(w.loud)}, unlock: ${w.unlock},
                modes: new[] { ${w.modes.map(mode).join(', ')} }, shellReload: ${!!w.shellReload}, scope: ${!!w.scope}, explosive: ${f(w.explosive || 0)}),`);

writeFileSync(join(assets, 'Scripts', 'Core', 'WeaponTable.g.cs'), `${header}using System.Collections.Generic;

namespace SpecialSoldier.Core
{
    public static partial class WeaponTable
    {
        public const float HeadMult = ${f(BODY_MULT.head)}, TorsoMult = ${f(BODY_MULT.torso)}, LimbMult = ${f(BODY_MULT.limb)};

        public static readonly IReadOnlyDictionary<string, WeaponStats> All = new Dictionary<string, WeaponStats>
        {
${rows.join('\n')}
        };
    }
}
`);

const dists = [5, 10, 20, 40, 90, 150, 200, 500];
const cases = [];
for (const [id, w] of Object.entries(WEAPONS)) {
  for (const dist of dists) cases.push(`            new ParityCase("${id}", ${dist}, damageAt: ${d(damageAt(w, dist))}, hitChance: ${d(hitChance(w, dist))}, effectiveDps: ${d(effectiveDps(w, dist))}),`);
}
const ttk = [];
for (const [id, w] of Object.entries(WEAPONS)) for (const [hp, armor] of [[90, 0], [110, 35], [150, 90], [260, 160]]) {
  const t = timeToKill(w, hp, armor, 20); ttk.push(`            new TtkCase("${id}", ${hp}, ${armor}, shots: ${t.shots}, time: ${d(t.time)}),`);
}
const burst = Object.entries(WEAPONS).map(([id, w]) => `            ["${id}"] = (${d(burstDps(w))}, ${d(cycleTime(w))}),`);

writeFileSync(join(assets, 'Tests', 'EditMode', 'BalanceFixture.g.cs'), `${header}using System.Collections.Generic;

namespace SpecialSoldier.Core.Tests
{
    public readonly struct ParityCase
    {
        public readonly string Id; public readonly float Dist; public readonly double DamageAt, HitChance, EffectiveDps;
        public ParityCase(string id, float dist, double damageAt, double hitChance, double effectiveDps) { Id = id; Dist = dist; DamageAt = damageAt; HitChance = hitChance; EffectiveDps = effectiveDps; }
        public override string ToString() => Id + "@" + Dist + "m";
    }

    public readonly struct TtkCase
    {
        public readonly string Id; public readonly float Hp, Armor; public readonly int Shots; public readonly double Time;
        public TtkCase(string id, float hp, float armor, int shots, double time) { Id = id; Hp = hp; Armor = armor; Shots = shots; Time = time; }
        public override string ToString() => Id + " vs " + Hp + "hp/" + Armor + "ar";
    }

    /// <summary>Values computed by the web game's JavaScript balance model (the reference implementation).</summary>
    public static class BalanceFixture
    {
        public static readonly ParityCase[] Cases =
        {
${cases.join('\n')}
        };

        public static readonly TtkCase[] Ttk =
        {
${ttk.join('\n')}
        };

        public static readonly Dictionary<string, (double burstDps, double cycleTime)> PerWeapon = new Dictionary<string, (double, double)>
        {
${burst.join('\n')}
        };
    }
}
`);
console.log(`[gen] ${Object.keys(WEAPONS).length} weapons, ${cases.length} parity cases, ${ttk.length} TTK cases`);
